import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHttpServer } from './server.mjs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { once } from 'node:events';
import { mkdtempSync, rmSync, statSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { createOAuth, hashOwnerPassword } from './oauth.mjs';

test('owner authorization, PKCE, redirect binding, token persistence and no unauthenticated access', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'beeper-oauth-'));
  const statePath = join(directory, 'oauth.json');
  const password = 'strong-owner-test-password-'.repeat(3);
  const config = { issuer: 'https://example.com/beeper/oauth', resource: 'https://example.com/beeper/mcp', statePath, ownerPasswordHash: hashOwnerPassword(password) };
  const oauth = createOAuth(config);
  const server = createHttpServer({ oauth, resourceMetadata: 'https://example.com/.well-known/oauth-protected-resource/beeper/mcp', beeperToken: 'backend-secret', backend: async () => ({ items: [] }) });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (path, body, options = {}) => fetch(base + path, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded', ...options.headers }, body: new URLSearchParams(body), redirect: options.redirect || 'follow' });
  try {
    const metadata = await (await fetch(base + '/.well-known/oauth-authorization-server/beeper/oauth')).json();
    assert.equal(metadata.issuer, config.issuer);
    assert.equal((await (await fetch(base + '/.well-known/oauth-protected-resource/beeper/mcp')).json()).resource, config.resource);
    async function register(uri) {
      return fetch(base + '/beeper/oauth/register', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ redirect_uris: [uri], token_endpoint_auth_method: 'none', grant_types: ['authorization_code', 'refresh_token'], response_types: ['code'] }) });
    }
    assert.equal((await register('https://evil.example/callback')).status, 400);
    const callback = 'https://chatgpt.com/connector_platform_oauth_redirect';
    const response = await register(callback); assert.equal(response.status, 201);
    const { client_id } = await response.json();
    const verifier = 'v'.repeat(64), challenge = createHash('sha256').update(verifier).digest('base64url');
    const params = new URLSearchParams({ response_type: 'code', client_id, redirect_uri: callback, code_challenge: challenge, code_challenge_method: 'S256', resource: config.resource, scope: 'messages:read', state: 'state123' });
    const formResponse = await fetch(`${base}/beeper/oauth/authorize?${params}`);
    const cookie = formResponse.headers.get('set-cookie').split(';')[0];
    assert.match(formResponse.headers.get('set-cookie'), /Secure; HttpOnly; SameSite=Strict/);
    const form = await formResponse.text();
    const nonce = form.match(/name="request" value="([^"]+)"/)[1];
    assert.equal((await post('/beeper/oauth/approve', { request: nonce, password })).status, 403);
    for (const headers of [{ Origin: 'https://evil.example', Cookie: cookie }, { Origin: 'null', 'Sec-Fetch-Site': 'cross-site', Cookie: cookie }, { Referer: 'https://evil.example/', Cookie: cookie }, { Origin: 'null' }]) assert.equal((await post('/beeper/oauth/approve', { request: nonce, password }, { headers })).status, 403);
    assert.equal((await post('/beeper/oauth/approve', { request: nonce, password: 'wrong' }, { headers: { Origin: 'https://example.com', Cookie: cookie } })).status, 401);
    const approve = await post('/beeper/oauth/approve', { request: nonce, password }, { headers: { Origin: 'null', Cookie: cookie }, redirect: 'manual' });
    assert.equal(approve.status, 303);
    const redirect = new URL(approve.headers.get('location')); assert.equal(redirect.origin + redirect.pathname, callback); assert.equal(redirect.searchParams.get('state'), 'state123');
    const code = redirect.searchParams.get('code');
    const grant = { grant_type: 'authorization_code', client_id, code, code_verifier: 'wrong-verifier', redirect_uri: callback, resource: config.resource };
    assert.equal((await post('/beeper/oauth/token', grant)).status, 400);
    assert.equal((await post('/beeper/oauth/token', { ...grant, code_verifier: verifier, resource: 'https://example.com/other' })).status, 400);
    assert.equal((await post('/beeper/oauth/token', { ...grant, code_verifier: verifier, redirect_uri: 'https://chatgpt.com/connector/oauth/wrong' })).status, 400);
    const tokenResponse = await post('/beeper/oauth/token', { ...grant, code_verifier: verifier });
    assert.equal(tokenResponse.status, 200); const { access_token, refresh_token } = await tokenResponse.json();
    assert.equal(oauth.validateBearer(access_token), true); assert.equal(oauth.subject(access_token), undefined); assert.equal(oauth.validateBearer('invalid'), false);
    const mcp = new Client({ name: 'oauth-integration-test', version: '1' });
    await mcp.connect(new StreamableHTTPClientTransport(new URL(base + '/mcp'), { requestInit: { headers: { Authorization: `Bearer ${access_token}` } } }));
    const tools = (await mcp.listTools()).tools;
    assert.ok(tools.some(tool => tool.name === 'list_accounts'));
    assert.ok(tools.every(tool => tool._meta?.securitySchemes?.[0]?.scopes?.includes('messages:read')));
    assert.equal((await mcp.callTool({ name: 'list_accounts', arguments: {} })).isError, undefined);
    await mcp.close();
    assert.equal((await post('/beeper/oauth/token', { ...grant, code_verifier: verifier })).status, 400);
    assert.equal(createOAuth(config).validateBearer(access_token), true);
    const secondClient = await (await register(callback)).json();
    const refreshGrant = { grant_type: 'refresh_token', client_id, refresh_token, resource: config.resource, scope: 'messages:read' };
    assert.equal((await post('/beeper/oauth/token', { ...refreshGrant, client_id: secondClient.client_id })).status, 400);
    assert.equal((await post('/beeper/oauth/token', { ...refreshGrant, resource: 'https://example.com/other' })).status, 400);
    assert.equal((await post('/beeper/oauth/token', { ...refreshGrant, scope: 'messages:write' })).status, 400);
    const rotatedResponse = await post('/beeper/oauth/token', refreshGrant);
    assert.equal(rotatedResponse.status, 200);
    const rotated = await rotatedResponse.json();
    assert.notEqual(rotated.refresh_token, refresh_token);
    assert.equal(oauth.validateBearer(rotated.access_token), true);
    const restartedOAuth = createOAuth(config);
    assert.equal(restartedOAuth.validateBearer(rotated.access_token), true);
    const restartedServer = createHttpServer({ oauth: restartedOAuth, resourceMetadata: 'https://example.com/.well-known/oauth-protected-resource/beeper/mcp', beeperToken: 'backend-secret', backend: async () => ({ items: [] }) });
    restartedServer.listen(0, '127.0.0.1'); await once(restartedServer, 'listening');
    try {
      const responseAfterRestart = await fetch(`http://127.0.0.1:${restartedServer.address().port}/beeper/oauth/token`, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ ...refreshGrant, refresh_token: rotated.refresh_token }) });
      assert.equal(responseAfterRestart.status, 200);
      const afterRestart = await responseAfterRestart.json();
      assert.equal(restartedOAuth.validateBearer(afterRestart.access_token), true);
      const replay = await fetch(`http://127.0.0.1:${restartedServer.address().port}/beeper/oauth/token`, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams(refreshGrant) });
      assert.equal(replay.status, 400);
      assert.equal(restartedOAuth.validateBearer(afterRestart.access_token), false);
      const revoked = await fetch(`http://127.0.0.1:${restartedServer.address().port}/beeper/oauth/token`, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ ...refreshGrant, refresh_token: afterRestart.refresh_token }) });
      assert.equal(revoked.status, 400);
    } finally { await new Promise(resolve => restartedServer.close(resolve)); }

    assert.equal(statSync(statePath).mode & 0o777, 0o600);
    assert.equal(readFileSync(statePath, 'utf8').includes(access_token), false);
    assert.equal(readFileSync(statePath, 'utf8').includes(rotated.refresh_token), false);
    assert.equal((await fetch(base + '/beeper/oauth/register', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ padding: 'x'.repeat(9000) }) })).status, 413);
    const sendParams = new URLSearchParams(params); sendParams.set('scope', 'messages:read messages:send');
    const directOAuth = createOAuth({ ...config, sendMode: 'direct' });
    const directServer = createHttpServer({ oauth: directOAuth, resourceMetadata: 'https://example.com/.well-known/oauth-protected-resource/beeper/mcp', beeperToken: 'backend-secret', backend: async () => ({ items: [] }), sendMode: 'direct' });
    directServer.listen(0, '127.0.0.1'); await once(directServer, 'listening');
    try {
      const consent = await (await fetch(`http://127.0.0.1:${directServer.address().port}/beeper/oauth/authorize?${sendParams}`)).text();
      assert.ok(consent.includes('envoi direct de messages sans confirmation'));
      assert.ok(!consent.includes('Chaque envoi exige'));
    } finally { await new Promise(resolve => directServer.close(resolve)); }
    const sendResponse = await fetch(`${base}/beeper/oauth/authorize?${sendParams}`);
    const sendCookie = sendResponse.headers.get('set-cookie').split(';')[0];
    const sendForm = await sendResponse.text();
    assert.ok(sendForm.includes('Chaque envoi exige'));
    const sendNonce = sendForm.match(/name="request" value="([^"]+)"/)[1];
    const sendApproval = await post('/beeper/oauth/approve', { request: sendNonce, password }, { headers: { Cookie: sendCookie, Referer: 'https://example.com/beeper/oauth/authorize' }, redirect: 'manual' });
    const sendCode = new URL(sendApproval.headers.get('location')).searchParams.get('code');
    const sendTokens = await (await post('/beeper/oauth/token', { ...grant, code: sendCode, code_verifier: verifier })).json();
    assert.equal(oauth.subject(sendTokens.access_token), client_id);
    assert.equal(oauth.subject(sendTokens.access_token, 'chats:start'), undefined);
    assert.equal(sendTokens.scope, 'messages:read messages:send');
    const startParams = new URLSearchParams(params); startParams.set('scope', 'messages:read chats:start');
    const startResponse = await fetch(`${base}/beeper/oauth/authorize?${startParams}`);
    const startCookie = startResponse.headers.get('set-cookie').split(';')[0];
    const startForm = await startResponse.text();
    assert.ok(startForm.includes('création ou ouverture de conversations WhatsApp'));
    const startNonce = startForm.match(/name="request" value="([^"]+)"/)[1];
    const startApproval = await post('/beeper/oauth/approve', { request: startNonce, password }, { headers: { Cookie: startCookie, Referer: 'https://example.com/beeper/oauth/authorize' }, redirect: 'manual' });
    const startCode = new URL(startApproval.headers.get('location')).searchParams.get('code');
    const startTokens = await (await post('/beeper/oauth/token', { ...grant, code: startCode, code_verifier: verifier })).json();
    assert.equal(oauth.subject(startTokens.access_token, 'chats:start'), client_id);
    assert.equal(oauth.subject(startTokens.access_token), undefined);
    const narrowed = await (await post('/beeper/oauth/token', { ...refreshGrant, refresh_token: sendTokens.refresh_token, scope: 'messages:read' })).json();
    assert.equal(oauth.subject(narrowed.access_token), undefined);
    const secondResponse = await fetch(`${base}/beeper/oauth/authorize?${params}`);
    const secondCookie = secondResponse.headers.get('set-cookie').split(';')[0];
    const secondForm = await secondResponse.text();
    const secondNonce = secondForm.match(/name="request" value="([^"]+)"/)[1];
    for (let i = 0; i < 4; i++) assert.equal((await post('/beeper/oauth/approve', { request: secondNonce, password: 'wrong' }, { headers: { Origin: 'https://example.com', Cookie: secondCookie } })).status, 401);
    assert.equal((await post('/beeper/oauth/approve', { request: secondNonce, password: 'wrong' }, { headers: { Origin: 'https://example.com', Cookie: secondCookie } })).status, 401);
    assert.equal((await post('/beeper/oauth/approve', { request: secondNonce, password }, { headers: { Origin: 'https://example.com', Cookie: secondCookie } })).status, 429);
  } finally { await new Promise(resolve => server.close(resolve)); rmSync(directory, { recursive: true, force: true }); }
});
